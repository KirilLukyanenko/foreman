using System.Text.RegularExpressions;

namespace Foreman.Recon.CodeMap;

/// <summary>A definition: a type, function, method, property, field. Lines are 1-based.</summary>
/// <param name="Id">For C#, Roslyn's documentation id (<c>M:Ns.Type.Method(System.Int32)</c>); null for tree-sitter.</param>
public sealed record CodeSymbol(string Name, string Kind, int Line, int EndLine, string Signature, string? Id = null);

/// <summary>A name used in a file and how often. For C#, <see cref="Id"/> is the exact symbol it resolves to.</summary>
public sealed record CodeRef(string Name, int Count, string? Id = null);

public sealed record FileTags(string Path, string Language, int Lines, IReadOnlyList<CodeSymbol> Defs, IReadOnlyList<CodeRef> Refs, string? Error = null);

/// <summary>Every parsed file of the repository with its definitions and references: the input of the map.</summary>
public sealed record CodeIndex(IReadOnlyList<FileTags> Files)
{
    public FileTags? Find(string path) => Files.FirstOrDefault(f => f.Path == path);
}

/// <summary>Which parser handles a file, by extension. C# goes to Roslyn, the rest to tree-sitter.</summary>
public static class CodeLanguages
{
    public const string CSharp = "csharp";

    private static readonly Dictionary<string, string> ByExtension = new(StringComparer.OrdinalIgnoreCase)
    {
        [".cs"] = CSharp,
        [".py"] = "python", [".pyi"] = "python",
        [".js"] = "javascript", [".mjs"] = "javascript", [".cjs"] = "javascript", [".jsx"] = "javascript",
        [".ts"] = "typescript", [".mts"] = "typescript", [".cts"] = "typescript",
        [".tsx"] = "tsx",
        [".go"] = "go",
        [".rs"] = "rust",
        [".java"] = "java",
        [".kt"] = "kotlin", [".kts"] = "kotlin",
        [".rb"] = "ruby",
        [".php"] = "php",
        [".c"] = "c", [".h"] = "c",
        [".cc"] = "cpp", [".cpp"] = "cpp", [".cxx"] = "cpp", [".hpp"] = "cpp", [".hh"] = "cpp",
        [".swift"] = "swift",
        [".scala"] = "scala",
    };

    public static string? For(string path)
    {
        if (path.EndsWith(".d.ts", StringComparison.OrdinalIgnoreCase) || path.EndsWith(".min.js", StringComparison.OrdinalIgnoreCase))
            return null;
        return ByExtension.GetValueOrDefault(Path.GetExtension(path));
    }
}

/// <summary>
/// Files a tool wrote and people don't edit: kept out of the map (they are noise there) and listed in the rules file
/// as files not to touch. Recognised by name and by the markers generators put in the first lines.
/// </summary>
public static partial class GeneratedFiles
{
    public static bool IsGenerated(string path, Func<string, string?> head)
    {
        if (GeneratedName().IsMatch(path)) return true;
        return head(path) is { } text && GeneratedMarker().IsMatch(text);
    }

    /// <summary>The first lines of a file, for the marker check.</summary>
    public static string? Head(string fullPath, int bytes = 1024)
    {
        try
        {
            using var stream = File.OpenRead(fullPath);
            var buffer = new byte[bytes];
            var n = stream.Read(buffer, 0, buffer.Length);
            return System.Text.Encoding.UTF8.GetString(buffer, 0, n);
        }
        catch (IOException)
        {
            return null;
        }
    }

    [GeneratedRegex(@"(\.g\.cs|\.g\.i\.cs|\.designer\.cs|\.generated\.\w+|\.pb\.go|_pb2\.pyi?|_pb2_grpc\.py|\.pb\.(cc|h)|_generated\.\w+|\.gen\.go)$", RegexOptions.IgnoreCase)]
    private static partial Regex GeneratedName();

    [GeneratedRegex(@"<auto-generated|Code generated .{0,80}DO NOT EDIT|@generated\b|(?-i:DO NOT EDIT)|This (file|code) was (automatically |auto-)?generated|automatically generated by", RegexOptions.IgnoreCase)]
    private static partial Regex GeneratedMarker();
}

/// <summary>What a path is for, from its folders and name.</summary>
public static partial class CodePaths
{
    private static readonly HashSet<string> TestDirs = new(StringComparer.OrdinalIgnoreCase)
        { "test", "tests", "spec", "specs", "__tests__", "__mocks__", "testing", "testdata", "fixtures", "e2e" };

    private static readonly HashSet<string> VendorDirs = new(StringComparer.OrdinalIgnoreCase)
        { "third_party", "thirdparty", "third-party", "vendor", "vendored", "external", "extern", "deps" };

    public static bool IsTest(string path)
    {
        var parts = path.Split('/');
        if (parts[..^1].Any(p => TestDirs.Contains(p) || p.EndsWith(".Tests", StringComparison.OrdinalIgnoreCase)
            || p.EndsWith(".UnitTests", StringComparison.OrdinalIgnoreCase) || p.EndsWith(".IntegrationTests", StringComparison.OrdinalIgnoreCase)))
            return true;
        return TestName().IsMatch(parts[^1]);
    }

    /// <summary>Code copied in from another project: not the client's to change, and noise in the map.</summary>
    public static bool IsVendored(string path) => path.Split('/')[..^1].Any(VendorDirs.Contains);

    [GeneratedRegex(@"^(test_.*\.py|.*_test\.(py|go)|(?-i:.*Tests?\.cs)|.*\.(test|spec)\.[cm]?[jt]sx?|.*_spec\.rb|(?-i:.*Test\.(java|kt)))$", RegexOptions.IgnoreCase)]
    private static partial Regex TestName();
}
